// ==================== 任务顺序与跳转辅助 ====================

// 任务ID列表（按建议顺序）
export const TASK_ORDER: TaskId[] = ['INFO', 'INTAKE', 'MATCHING', 'BUDGET', 'SUMMARY', 'HANDOFF'];

// 下一个任务（按建议顺序）
export function getNextTaskId(currentId: TaskId): TaskId | null {
  const idx = TASK_ORDER.indexOf(currentId);
  if (idx === -1 || idx >= TASK_ORDER.length - 1) return null;
  return TASK_ORDER[idx + 1];
}

// 上一个任务
export function getPrevTaskId(currentId: TaskId): TaskId | null {
  const idx = TASK_ORDER.indexOf(currentId);
  if (idx <= 0) return null;
  return TASK_ORDER[idx - 1];
}

// 根据ID获取任务
export function getTaskById(id: TaskId): Task | undefined {
  return TASKS.find((t) => t.id === id);
}

// ==================== 3项必填检查 ====================

// v4.0 预约必要信息只有3项：
// 1. 预约/服务目标（intent + core_topics 至少有内容）
// 2. 可联系方式或明确拒绝（contact_method 已填写，含 none_refused）
// 3. 城市/国家或时区（city 或 country 或 timezone 至少有一个）
export interface RequiredFieldsCheck {
  allRequired: boolean;
  missing: string[];
  details: Record<string, boolean>;
}

export function checkRequiredFields(fields: {
  intent?: string;
  core_topics?: string[];
  core_topics_open?: string;
  contact_method?: string;
  city?: string;
  country?: string;
  timezone?: string;
}): RequiredFieldsCheck {
  const details: Record<string, boolean> = {
    intent_or_goal: !!(fields.intent && (fields.core_topics && fields.core_topics.length > 0 || fields.core_topics_open)),
    contact_info: !!fields.contact_method, // 包括 none_refused（明确拒绝也算）
    location: !!(fields.city || fields.country || fields.timezone),
  };

  const missing = Object.entries(details)
    .filter(([, v]) => !v)
    .map(([k]) => k);

  return {
    allRequired: missing.length === 0,
    missing,
    details,
  };
}

// ==================== 辅助函数 ====================

// 按名称查找心理师（支持中文名/英文名/全名）
export function findTherapistByName(name: string): Therapist | undefined {
  const lower = name.toLowerCase().trim();
  return THERAPISTS.find(
    (t) =>
      t.name === name ||
      t.name_en.toLowerCase() === lower || `${t.name} ${t.name_en}`.toLowerCase() === lower ||
      t.name.toLowerCase().includes(lower) ||
      t.name_en.toLowerCase().includes(lower),
  );
}

// 按价格档位获取心理师
export function getTherapistsByPrice(maxPrice: number): Therapist[] {
  return THERAPISTS.filter((t) => t.price <= maxPrice && t.role === '心理师');
}

// 按推荐顺序排序
export function sortTherapistsByOrder(therapists: Therapist[]): Therapist[] {
  return [...therapists].sort((a, b) => {
    const aKey = `${a.name} ${a.name_en}`;
    const bKey = `${b.name} ${b.name_en}`;
    const aIdx = THERAPIST_ORDER.indexOf(aKey);
    const bIdx = THERAPIST_ORDER.indexOf(bKey);
    if (aIdx === -1 && bIdx === -1) return 0;
    if (aIdx === -1) return 1;
    if (bIdx === -1) return -1;
    return aIdx - bIdx;
  });
}
