// ===== 工具函数 =====
export function getDimensionContent(code: BFDimensionCode): BFDimensionContent {
  return BF_DIMENSIONS[code];
}

export function getAllDimensionNames(): { code: BFDimensionCode; name_cn: string; name_en: string }[] {
  return (Object.keys(BF_DIMENSIONS) as BFDimensionCode[]).map(code => ({
    code,
    name_cn: BF_DIMENSIONS[code].name_cn,
    name_en: BF_DIMENSIONS[code].name_en,
  }));
}

