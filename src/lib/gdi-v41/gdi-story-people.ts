export const getPublicReadyPeople = (): StoryPerson[] => {
  return GDI_STORY_PEOPLE.filter((p) => p.reviewStatus === 'public_ready');
};

// 按领域获取人物
export const getPeopleByField = (field: string): StoryPerson[] => {
  return GDI_STORY_PEOPLE.filter((p) => p.field === field);
};

// 根据主题匹配人物（行为镜像，不做身份匹配）
export const matchPeopleByThemes = (
  themes: string[],
  count: number = 3
): StoryPerson[] => {
  const themeSet = new Set(themes);
  const scored = GDI_STORY_PEOPLE
    .filter((p) => p.reviewStatus === 'public_ready')
    .map((p) => {
      const matches = p.behavioralThemes.filter((t) => themeSet.has(t)).length;
      return { person: p, matches };
    })
    .filter((s) => s.matches > 0)
    .sort((a, b) => b.matches - a.matches);
  
  if (scored.length < count) {
    // 如果匹配不够，补充随机人物
    const remaining = GDI_STORY_PEOPLE.filter(
      (p) => p.reviewStatus === 'public_ready' && !scored.find((s) => s.person.id === p.id)
    );
    const shuffled = [...remaining].sort(() => Math.random() - 0.5);
    const needed = count - scored.length;
    for (let i = 0; i < needed && i < shuffled.length; i++) {
      scored.push({ person: shuffled[i], matches: 0 });
    }
  }
  
  return scored.slice(0, count).map((s) => s.person);
};

