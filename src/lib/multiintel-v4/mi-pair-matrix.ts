// 验证：28 组
export function validatePairCount(): { count: number; valid: boolean } {
  const count = pairMatrixDefinitions.length;
  // 8 选 2 = 28
  return { count, valid: count === 28 };
}

// 按关系类型筛选
export function getPairsByRelation(relation: PairRelationType): PairMatrixDefinition[] {
  return pairMatrixDefinitions.filter((p) => p.relation === relation);
}

// 获取特定组合的定义
export function getPairDefinition(
  d1: DimensionCode,
  d2: DimensionCode,
): PairMatrixDefinition | undefined {
  return pairMatrixDefinitions.find(
    (p) =>
      (p.pair[0] === d1 && p.pair[1] === d2) ||
      (p.pair[0] === d2 && p.pair[1] === d1),
  );
}
