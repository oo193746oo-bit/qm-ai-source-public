// 根据维度对获取Pair叙事
export const getPairNarratives = (
  a: DimensionCode,
  b: DimensionCode
): PairCombination | undefined => {
  const keyA = `${a}_${b}`;
  const keyB = `${b}_${a}`;
  return GDI_PAIR_MATRIX.find((p) => p.key === keyA || p.key === keyB);
};

// 根据分数获取最匹配的叙事类型
export const getPairNarrativeType = (
  scoreA: number | null,
  scoreB: number | null
): 'highHigh' | 'highLow' | 'lowHigh' | 'lowLow' | 'mixed' => {
  if (scoreA === null || scoreB === null) return 'mixed';

  const aHigh = scoreA >= 66;
  const aLow = scoreA < 33;
  const bHigh = scoreB >= 66;
  const bLow = scoreB < 33;

  if (aHigh && bHigh) return 'highHigh';
  if (aHigh && bLow) return 'highLow';
  if (aLow && bHigh) return 'lowHigh';
  if (aLow && bLow) return 'lowLow';
  return 'mixed';
};
