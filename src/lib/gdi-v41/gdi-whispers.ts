// 随机选取n条耳语
export const getRandomWhispers = (n: number, filter?: Partial<Whisper>): Whisper[] => {
  let pool = [...GDI_WHISPERS];
  if (filter) {
    for (const [key, value] of Object.entries(filter)) {
      pool = pool.filter((w) => (w as any)[key] === value);
    }
  }
  // Fisher-Yates shuffle
  for (let i = pool.length - 1; i > 0; i--) {
    const j = Math.floor(Math.random() * (i + 1));
    [pool[i], pool[j]] = [pool[j], pool[i]];
  }
  return pool.slice(0, Math.min(n, pool.length));
};

// 根据画像推荐耳语
export const recommendWhispersForProfile = (
  profile: any,
  count: number = 12
): Whisper[] => {
  const selected: Whisper[] = [];
  
  const dims: DimensionCode[] = ['IGS', 'SDO', 'EA', 'CF', 'GCC', 'GAE', 'SNA', 'BR'];
  const scoredDims = dims
    .filter((d) => !profile.scores[d]?.incomplete && profile.plotScores[d] !== null)
    .sort((a, b) => (profile.plotScores[a] ?? 0) - (profile.plotScores[b] ?? 0));
  
  const lowDims = scoredDims.slice(0, 3);
  const highDims = scoredDims.slice(-2);
  
  // 低分维度各取2条支持性耳语
  for (const dim of lowDims) {
    const dimWhispers = GDI_WHISPERS.filter((w) => w.dimension === dim && w.category === 'single_dimension');
    const shuffled = [...dimWhispers].sort(() => Math.random() - 0.5);
    selected.push(...shuffled.slice(0, 2));
  }
  
  // 高分维度各取1条肯定性耳语
  for (const dim of highDims) {
    const dimWhispers = GDI_WHISPERS.filter((w) => w.dimension === dim && w.category === 'single_dimension');
    const shuffled = [...dimWhispers].sort(() => Math.random() - 0.5);
    selected.push(...shuffled.slice(0, 1));
  }
  
  // 取2条情境耳语
  const contextWhispers = GDI_WHISPERS.filter((w) => w.category === 'context');
  const shuffledCtx = [...contextWhispers].sort(() => Math.random() - 0.5);
  selected.push(...shuffledCtx.slice(0, 2));
  
  // 取1条文化/身份耳语
  const cultureWhispers = GDI_WHISPERS.filter((w) => w.category === 'identity_culture');
  const shuffledCulture = [...cultureWhispers].sort(() => Math.random() - 0.5);
  selected.push(...shuffledCulture.slice(0, 1));
  
  // 如果不够，用Pair耳语补齐
  if (selected.length < count) {
    const pairWhispers = GDI_WHISPERS.filter(
      (w) => w.category === 'pair' && !selected.find((s) => s.id === w.id)
    );
    const shuffledPair = [...pairWhispers].sort(() => Math.random() - 0.5);
    selected.push(...shuffledPair.slice(0, count - selected.length));
  }
  
  // 打乱顺序
  return selected.sort(() => Math.random() - 0.5).slice(0, count);
};

// 获取一个随机开放问题
export const getRandomOpenQuestion = (): Whisper => {
  const questions = GDI_WHISPERS.filter((w) => w.category === 'open_question');
  return questions[Math.floor(Math.random() * questions.length)];
};
