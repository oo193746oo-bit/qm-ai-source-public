/** 根据tool_id获取工具 */
export function getToolById(toolId: string): Tool | undefined {
  return TOOL_REGISTRY.find((t) => t.tool_id === toolId);
}

/** 根据类别ID获取工具列表 */
export function getToolsByCategory(categoryId: string): Tool[] {
  return TOOL_REGISTRY.filter((t) => t.category_id === categoryId);
}

/** 搜索工具（名称、关键词、场景、机制） */
export function searchTools(query: string): Tool[] {
  const q = query.trim().toLowerCase();
  if (!q) return TOOL_REGISTRY;
  return TOOL_REGISTRY.filter((t) => {
    return (
      t.name.toLowerCase().includes(q) ||
      t.mechanism.toLowerCase().includes(q) ||
      t.keywords.some((k) => k.toLowerCase().includes(q)) ||
      t.scenarios.some((s) => s.toLowerCase().includes(q)) ||
      t.category_name.toLowerCase().includes(q)
    );
  });
}

/** 获取工具总数 */
export function getToolCount(): number {
  return TOOL_REGISTRY.length;
}

/** 获取类别及其工具数量 */
export function getCategoriesWithCount(): Array<ToolCategory & { count: number }> {
  return CATEGORIES.map((cat) => ({
    ...cat,
    count: TOOL_REGISTRY.filter((t) => t.category_id === cat.id).length,
  }));
}