export const PERSON_STORY_COUNT = wvPersonStories.length;

export function getPublicReadyPeople(): PersonStory[] {
  return wvPersonStories.filter((p) => p.reviewStatus === 'public_ready');
}

export function findPeopleByValues(
  targetValues: string[],
  limit = 5,
): PersonStory[] {
  const scored = wvPersonStories
    .filter((p) => p.reviewStatus === 'public_ready')
    .map((p) => {
      const matches = p.connectedValues.filter((v) =>
        targetValues.includes(v),
      ).length;
      return { person: p, score: matches };
    })
    .filter((s) => s.score > 0)
    .sort((a, b) => b.score - a.score);
  return scored.slice(0, limit).map((s) => s.person);
}

export function validatePersonStories(): { total: number; publicReady: number; valid: boolean } {
  const publicReady = wvPersonStories.filter((p) => p.reviewStatus === 'public_ready').length;
  return {
    total: wvPersonStories.length,
    publicReady,
    valid: publicReady >= 300,
  };
}
