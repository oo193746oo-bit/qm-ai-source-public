// ===== 工具函数 =====
export function getPairNarrative(pairKey: string): BFPairNarrative | undefined {
  // 接受 'O×C' 或 'C×O' 两种顺序
  return BF_COMBINATIONS.find(
    p => p.pair === pairKey || p.pair === pairKey.split('×').reverse().join('×')
  );
}

export function getTensionPairsForProfile(pairList: string[]): BFPairNarrative[] {
  return pairList
    .map(p => getPairNarrative(p))
    .filter((p): p is BFPairNarrative => p !== undefined);
}

