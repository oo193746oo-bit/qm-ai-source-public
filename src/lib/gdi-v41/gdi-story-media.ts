// 按类型获取作品
export const getMediaByType = (type: StoryMedia['type']): StoryMedia[] => {
  return GDI_STORY_MEDIA.filter((m) => m.type === type);
};

// 根据主题匹配作品（行为镜像）
export const matchMediaByThemes = (
  themes: string[],
  count: number = 3
): StoryMedia[] => {
  const themeSet = new Set(themes);
  const scored = GDI_STORY_MEDIA
    .filter((m) => m.reviewStatus === 'public_ready')
    .map((m) => {
      const matches = m.themes.filter((t) => themeSet.has(t)).length +
        m.behavioralMirrors.filter((t) => themeSet.has(t)).length;
      return { media: m, matches };
    })
    .filter((s) => s.matches > 0)
    .sort((a, b) => b.matches - a.matches);

  if (scored.length < count) {
    // 不够时补充随机
    const remaining = GDI_STORY_MEDIA.filter(
      (m) => m.reviewStatus === 'public_ready' && !scored.find((s) => s.media.id === m.id)
    );
    const shuffled = [...remaining].sort(() => Math.random() - 0.5);
    const needed = count - scored.length;
    for (let i = 0; i < needed && i < shuffled.length; i++) {
      scored.push({ media: shuffled[i], matches: 0 });
    }
  }

  return scored.slice(0, count).map((s) => s.media);
};

