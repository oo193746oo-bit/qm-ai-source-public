/**
 * 全文搜索（只搜 public_ready）
 * 搜索范围：标题(权重4)、摘要(权重3)、子议题(权重2)、正文(权重1)
 * 空搜索返回全部公开文章
 */
export function searchContent(query: string): KnowledgeContent[] {
  const q = query.toLowerCase().trim();
  const allPublic = getPublicContent();

  if (!q) return allPublic;

  const scored: { content: KnowledgeContent; score: number }[] = [];

  // P1.8 H6：海外信号检测
  const OVERSEAS_SIGNAL_WORDS = [
    "海外", "时差", "留学", "留学生", "出国", "移民", "旅居", "境外",
    "foreign", "abroad", "国外", "外国",
  ];
  const hasOverseasSignal = OVERSEAS_SIGNAL_WORDS.some(word => q.includes(word));

  for (const c of allPublic) {
    let score = 0;
    const title = c.title.toLowerCase();
    const summary = c.public_summary.toLowerCase();
    const subtopic = c.subtopic.toLowerCase();
    const domain = c.domain.toLowerCase();

    if (title.includes(q)) score += 4;
    if (summary.includes(q)) score += 3;
    if (subtopic.includes(q)) score += 2;
    if (domain.includes(q)) score += 1;

    // 正文搜索（从 article-bodies 获取）
    const body = getArticleBody(c.content_id);
    if (body && body.body_markdown.toLowerCase().includes(q)) {
      score += 1;
    }

    if (score > 0) {
      // P1.8 H6：海外文章硬排除（境内场景）
      // 用户消息无海外信号时，overseas 标记文章不得进入传给模型的参考片段集
      const OVERSEAS_MARKERS = ["海外", "时差", "留学", "出国", "移民", "旅居", "境外"];
      const isOverseas = OVERSEAS_MARKERS.some(marker => title.includes(marker) || summary.includes(marker));
      if (!hasOverseasSignal && isOverseas) {
        continue; // 硬排除，不参与评分竞争
      }
      
      scored.push({ content: c, score });
    }
  }

  return scored.sort((a, b) => b.score - a.score).map((s) => s.content);
}

/** 获取领域下的子议题列表 */
export function getSubtopicsByDomain(domainId: string): string[] {
  const items = getContentByDomain(domainId);
  const subtopics = new Set(items.map((c) => c.subtopic));
  return Array.from(subtopics);
}

