// 获取维度名称
export function getDimensionName(code: DimensionCode): string {
  return wvDimensions[code]?.name || code;
}

// 获取维度颜色
export function getDimensionColor(code: DimensionCode): string {
  return wvDimensions[code]?.color || '#6B4C9A';
}

// 按 Value Map 坐标获取所有维度
export function getValueMapPoints(): Array<{
  code: DimensionCode;
  name: string;
  x: number;
  y: number;
  color: string;
}> {
  return (Object.keys(wvDimensions) as DimensionCode[]).map((code) => ({
    code,
    name: wvDimensions[code].name,
    x: wvDimensions[code].valueMap.x,
    y: wvDimensions[code].valueMap.y,
    color: wvDimensions[code].color,
  }));
}
