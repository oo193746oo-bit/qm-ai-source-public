// 验证函数：检查是否有禁词
export function validateWhispers(): { total: number; forbiddenErrors: string[] } {
  const forbidden = [
    '天生', '核心天赋', '你不擅长', '咨询师', '400', '120', '110',
  ];
  const errors: string[] = [];
  for (const w of whispers) {
    for (const word of forbidden) {
      if (w.text.includes(word)) {
        errors.push(`${w.id} contains forbidden word: ${word}`);
      }
    }
  }
  return { total: whispers.length, forbiddenErrors: errors };
}