/**
 * 根据 type_code + clarity + 边界维度 + 年龄 + 文化 + 当前关注点 + 展示历史
 * 选择 3-5 条耳语，避免重复
 */
export function selectWhispers(
  typeCode: TypeCode,
  context: PersonalizationContext,
  count: number = 4
): WhisperModule[] {
  const pool = WHISPER_LIBRARY[typeCode] || [];
  const shownIds = new Set(context.shownWhisperIds);
  
  // 过滤已展示过的
  let candidates = pool.filter(w => !shownIds.has(w.id));
  
  // 如果都展示过了，就重置（全部可用）
  if (candidates.length < count) {
    candidates = [...pool];
  }
  
  // 如果有当前关注点，优先匹配相关耳语
  if (context.currentConcern) {
    const concern = context.currentConcern.toLowerCase();
    const matched = candidates.filter(w =>
      w.focusArea?.toLowerCase().includes(concern) ||
      w.content.seeing.toLowerCase().includes(concern) ||
      w.content.growth.toLowerCase().includes(concern)
    );
    if (matched.length >= count) {
      candidates = matched;
    }
  }
  
  // 随机打乱并选取
  const shuffled = [...candidates];
  for (let i = shuffled.length - 1; i > 0; i--) {
    const j = Math.floor(Math.random() * (i + 1));
    [shuffled[i], shuffled[j]] = [shuffled[j], shuffled[i]];
  }
  
  return shuffled.slice(0, Math.min(count, shuffled.length));
}
